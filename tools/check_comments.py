#!/usr/bin/env python3
"""check_comments.py - checks the comment rules in CONTRIBUTING.md ("Comments") on the .asm sources.

  python3 tools/check_comments.py [--summary] [--rule R[,R...]] [FILE...]   (default: every file under src/)

Rules (the name in brackets is what --rule takes):
  [width]    no line that carries a comment is wider than 110 columns (data lines such as `db ...  ; insn:` aside)
  [column]   a comment after an instruction starts at column 48, or one space after code that reaches past it
  [para]     a paragraph of a routine header or block comment (split by a `;` line) has at most 3 lines
  [header]   every routine has a header between rule lines, with a description under the name line
  [data]     every data label (a variable, table or string) has a comment on its line
  [ida]      no IDA names in comments (sub_, loc_, unk_, dword_, byte_, word_, off_, asc_, jpt_, nullsub_)
  [lineage]  no other game's name in comments (94G, NHL 95, Genesis ...): lineage lives in docs/name_map.csv;
             the SOURCE field on a header's name line is the one exception
  [segment]  no segment numbers (seg022) or generator words in comments: name the routine or the file
  [file]     the file starts with a comment line that says what the file holds
--summary prints a count per rule and per folder instead of every line. Exit status 1 when anything is reported.
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import format_asm

WIDTH, COL, MAXPARA = 110, 48, 3
RULE = ';' + '-' * 77
LABEL = re.compile(r'^([A-Za-z_][\w$?@.]*):(.*)$')
IDA = re.compile(r'\b(sub|loc|unk|dword|byte|off|qword|asc|jpt|nullsub|flt|dbl|stru|algn)_[0-9A-F]{4,}\b')
LINEAGE = re.compile(r'\b(9[2-7][GS]|NHLPA ?93|NHL ?9[2-7]|9[2-7] ?(PC|Genesis|SNES)|(Genesis|SNES|Sega)\b)', re.I)
SEGWORD = re.compile(r'\bseg\d{3}\b|generated by', re.I)
DATA_OP = re.compile(r'^(db|dw|dd|dq|dt|resb|resw|resd|times|incbin|align|alignb)\b', re.I)
NOFALL = ('ret', 'retf', 'retn', 'jmp', 'iret', 'hlt')
RULES = 'width column para header data ida lineage segment file'.split()
split = format_asm.split


def is_code(l):
    """an instruction line (an instruction kept as bytes counts)"""
    if not l.startswith(' ') or not l.strip() or l.strip().startswith(';'): return False
    code, cm = split(l)
    c = code.strip()
    if not c: return False
    if DATA_OP.match(c): return cm is not None and cm[1:].strip().startswith('insn:')
    if len(c.split()) > 1 and DATA_OP.match(c.split(None, 1)[1]): return False      # name db ...
    return True


def opcode(l):
    code, cm = split(l)
    c = code.strip()
    if DATA_OP.match(c) and cm: c = cm[1:].strip()[5:].strip()
    return c.split()[0].lower() if c else ''


def routine_starts(L):
    """indices of the global labels that start a routine: code follows, and the code before (if any) does not run
    into it"""
    out = []
    for k, l in enumerate(L):
        m = re.match(r'^([A-Za-z_][\w$?@]*):', l)
        if not m: continue
        prev = None
        for j in range(k - 1, -1, -1):
            s = L[j].strip()
            if not s or s.startswith(';') or s.startswith('%'): continue
            prev = j; break
        if prev is not None:
            if LABEL.match(L[prev]): continue                       # alias of the label above
            if is_code(L[prev]) and opcode(L[prev]) not in NOFALL: continue   # code above runs into it
        nxt = None
        for j in range(k + 1, len(L)):
            s = L[j].strip()
            if not s or s.startswith(';') or s.startswith('%') or LABEL.match(s): continue
            nxt = L[j]; break
        if nxt is not None and is_code(nxt): out.append(k)
    return out


def check(path):
    out = []
    L = open(path, encoding='latin1').read().split('\n')
    starts = set(routine_starts(L))
    top = []
    for l in L:
        if l.startswith(';'): top.append(l)
        elif l.strip(): break
    if not any(t.strip(';').strip() and not SEGWORD.search(t) for t in top):
        out.append((1, 'file', 'no file header saying what the file holds'))
    in_header = False
    for n, l in enumerate(L, 1):
        code, cm = split(l)
        if l.startswith(RULE): in_header = not in_header
        if cm is None: continue
        body = cm.lstrip(';')
        name_line = in_header and n >= 2 and L[n - 2].startswith(RULE)
        if len(l.expandtabs(8)) > WIDTH and not DATA_OP.match(code.strip()) and 'insn:' not in cm:
            out.append((n, 'width', 'line is %d columns wide (max %d)' % (len(l.expandtabs(8)), WIDTH)))
        if code.strip() and not code.lstrip().startswith('%'):
            w = len(code.rstrip().expandtabs(8)); pos = len(code.expandtabs(8))
            if not ((w < COL and pos == COL) or (w >= COL and pos == w + 1)):
                out.append((n, 'column', 'comment at column %d (expected %d)' % (pos, COL)))
        m = IDA.search(body)
        if m and not l.startswith(RULE): out.append((n, 'ida', 'IDA name %s in a comment' % m.group(0)))
        if not name_line and 'insn:' not in cm:
            m = LINEAGE.search(body)
            if m: out.append((n, 'lineage', 'other game named in a comment: %s' % m.group(0)))
            m = SEGWORD.search(body)
            if m: out.append((n, 'segment', 'segment number or generator word in a comment: %s' % m.group(0)))
    i = 0
    while i < len(L):
        if L[i].startswith(';') and not L[i].startswith(RULE) and i > 0:
            j = i
            while j < len(L) and L[j].startswith(';') and not L[j].startswith(RULE): j += 1
            para = start = 0
            for k in range(i, j + 1):
                if k == j or re.match(r'^;\s*$', L[k]):
                    if para > MAXPARA: out.append((start + 1, 'para', 'comment paragraph of %d lines (max %d)' % (para, MAXPARA)))
                    para = 0
                else:
                    if para == 0: start = k
                    para += 1
            i = j
        i += 1
    for k in sorted(starts):
        name = L[k].split(':')[0]
        c = k
        while c > 0 and L[c - 1].startswith((';', '%')) and not L[c - 1].startswith(RULE): c -= 1
        if not (c > 0 and L[c - 1].startswith(RULE)):
            out.append((k + 1, 'header', 'routine %s has no header' % name)); continue
        b = c - 2
        while b > 0 and not L[b].startswith(RULE): b -= 1
        if c - 1 - b < 3: out.append((k + 1, 'header', 'header of %s has no description' % name))
    for k, l in enumerate(L):
        m = LABEL.match(l)
        if not m or k in starts or m.group(1).startswith('.'): continue
        nxt = None
        for j in range(k + 1, min(k + 40, len(L))):
            s = L[j]
            if not s.strip() or s.startswith((';', '%')) or LABEL.match(s): continue
            nxt = s; break
        if nxt is None or is_code(nxt) or not DATA_OP.match(nxt.strip()): continue
        if split(l)[1] is None: out.append((k + 1, 'data', 'data label %s has no comment' % m.group(1)))
    return out


def main(argv):
    summary = '--summary' in argv
    only = None
    if '--rule' in argv:
        only = set(argv[argv.index('--rule') + 1].split(','))
        del argv[argv.index('--rule'):argv.index('--rule') + 2]
    paths = format_asm.files([a for a in argv if not a.startswith('--')])
    count = {}; total = 0
    for p in paths:
        rel = os.path.relpath(p, format_asm.SRC).split(os.sep)
        top = '/'.join(rel[:2]) if len(rel) > 2 else rel[0]
        for n, r, msg in check(p):
            if only and r not in only: continue
            total += 1
            count.setdefault(r, {}).setdefault(top, 0); count[r][top] += 1
            if not summary:
                try: print('%s:%d: [%s] %s' % (os.path.relpath(p), n, r, msg))
                except BrokenPipeError: return 1
    if summary:
        for r in RULES:
            if r in count:
                print('%-8s %6d  %s' % (r, sum(count[r].values()),
                                        ', '.join('%s %d' % kv for kv in sorted(count[r].items(), key=lambda x: -x[1]))))
    print('%d comment problem(s)' % total if total else 'comments OK')
    return 1 if total else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
